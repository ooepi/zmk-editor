// Generates src/core/catalog/keycodes.data.ts from ZMK's dt-bindings/zmk/keys.h.
// Usage: node scripts/gen-keycodes.mjs [ref]   (default ref: v0.3)
import { writeFileSync } from 'node:fs';

const ref = process.argv[2] ?? 'v0.3';
const url = `https://raw.githubusercontent.com/zmkfirmware/zmk/${ref}/app/include/dt-bindings/zmk/keys.h`;
const response = await fetch(url);
if (!response.ok) throw new Error(`${url}: ${response.status}`);
const source = (await response.text()).replace(/\\\n\s*/g, ' ');

/** `#define NAME (0x04)` values from a header next to keys.h. */
async function defines(header) {
  const res = await fetch(url.replace('keys.h', header));
  if (!res.ok) throw new Error(`${header}: ${res.status}`);
  const values = new Map();
  for (const m of (await res.text()).matchAll(/^#define\s+(\w+)\s+\(?(0x[0-9A-Fa-f]+|\d+)\)?/gm)) values.set(m[1], Number(m[2]));
  return values;
}
const ids = await defines('hid_usage.h');
const pages = await defines('hid_usage_pages.h');
/** Modifier bits from modifiers.h, applied as `mods << 24`. */
const MOD_BITS = { LC: 0x01, LS: 0x02, LA: 0x04, LG: 0x08, RC: 0x10, RS: 0x20, RA: 0x40, RG: 0x80 };

const entries = [];
let description = '';
for (const line of source.split('\n')) {
  const comment = /^\/\*\s*(.*?)\s*\*\/$/.exec(line);
  if (comment) {
    description = comment[1];
    continue;
  }
  const [code, trailing = ''] = line.split('//');
  const define = /^#define\s+(\w+)\s+\((.*)\)\s*$/.exec(code);
  if (!define) continue;
  const [, name, value] = define;
  const deprecated = /DEPRECATED/.test(trailing);
  const alias = /^\w+$/.test(value) ? entries.find((e) => e.name === value) : undefined;
  if (alias) {
    (deprecated ? alias.deprecated : alias.aliases).push(name);
    continue;
  }
  const usage = /ZMK_HID_USAGE\((HID_USAGE_\w+),\s*(\w+)\)/.exec(value);
  if (!usage) continue;
  const page = { HID_USAGE_KEY: 'key', HID_USAGE_CONSUMER: 'consumer', HID_USAGE_GD: 'gd' }[usage[1]];
  if (!page) continue;
  const pageValue = pages.get(usage[1]);
  const id = /^(0x[0-9A-Fa-f]+|\d+)$/.test(usage[2]) ? Number(usage[2]) : ids.get(usage[2]);
  if (pageValue === undefined || id === undefined) throw new Error(`Can't resolve ${name}: ${value}`);
  const mods = [...value.matchAll(/\b(L[CSAG]|R[CSAG])\(/g)].reduce((bits, m) => bits | MOD_BITS[m[1]], 0);
  const usageValue = ((mods << 24) >>> 0) + ((pageValue << 16) | id);
  entries.push({ name, aliases: [], deprecated: [], description, page, shifted: /^\(?LS\(/.test(value), usage: usageValue });
}

const out = `// Generated by scripts/gen-keycodes.mjs from ZMK ${ref} keys.h. Do not edit.

export interface KeycodeData {
  /** Canonical name. */
  name: string;
  aliases: string[];
  deprecated: string[];
  description: string;
  page: 'key' | 'consumer' | 'gd';
  /** Defined as LS(...) of another key, e.g. EXCLAMATION. */
  shifted: boolean;
  /** The value ZMK sends for it: (page << 16) | id, with modifier bits (LS…) in bits 24–31. */
  usage: number;
}

export const KEYCODE_DATA: KeycodeData[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(new URL('../src/core/catalog/keycodes.data.ts', import.meta.url), out);
console.log(`Wrote ${entries.length} keycodes`);
